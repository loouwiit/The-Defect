#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
从 Rime 词库提取「拼音 → 单字」映射，生成 ESP32-P4 LVGL IME 自定义词库。

数据源：Rime《通用规范汉字表》8105 字字表 (cn_dicts/8105.dict.yaml)
  - 格式：字<TAB>拼音<TAB>权重（sort: by_weight，25 亿字语料权威字频）
  - ü 系以 v 代（lv/nv/lve/nve），与 LVGL 键盘输入约定一致

输出：resourse/system/pinyin_dict.txt（FAT 上传到 /root/system/）
  - 格式：拼音<TAB>汉字直接连接（无分隔符，紧凑，每字 3 字节 UTF-8）
  - 拼音按字典序排列（LVGL 前缀匹配要求，短音在前）
  - 组内按权重降序（常用字靠前，翻页可访问全部）

约束：
  - 仅单字
  - 过滤非 3 字节 UTF-8 字（CJK 扩展区等，LVGL 候选缓冲 lv_pinyin_cand_str[][4] 仅支持 3 字节）
  - 拼音仅 [a-z]+

用法：
  python3 tools/gen_pinyin_dict.py [--input 源文件] [--output 输出文件]
"""

import argparse
import os
import re
import sys
from collections import defaultdict

PY_RE = re.compile(r'^[a-z]+$')


def parse_dict(path):
    """解析 Rime .dict.yaml，返回 ({pinyin: [(char, weight)]}, 过滤清单)"""
    groups = defaultdict(list)
    filtered = []  # (char, pinyin, weight, reason)
    with open(path, encoding='utf-8') as f:
        for line in f:
            line = line.rstrip('\n').rstrip('\r')
            if not line or line.startswith('#') or \
               line.startswith('---') or line.startswith('...'):
                continue
            parts = line.split('\t')
            if len(parts) < 2:
                continue
            ch, pinyin = parts[0], parts[1]
            weight = int(parts[2].strip()) if len(parts) >= 3 and parts[2].strip().isdigit() else 0

            # 仅单字
            if len(ch) != 1:
                continue
            # 过滤非 3 字节 UTF-8（CJK 扩展区等）
            if len(ch.encode('utf-8')) != 3:
                filtered.append((ch, pinyin, weight, '非3字节UTF-8'))
                continue
            # 拼音校验
            if not PY_RE.fullmatch(pinyin):
                filtered.append((ch, pinyin, weight, '非法拼音'))
                continue

            groups[pinyin].append((ch, weight))
    return groups, filtered


def main():
    ap = argparse.ArgumentParser(description='生成 LVGL IME 拼音词库')
    ap.add_argument('--input',
                    default=os.path.expanduser('~/.config/ibus/rime/cn_dicts/8105.dict.yaml'),
                    help='Rime 字表源文件（默认 ~/.config/ibus/rime/cn_dicts/8105.dict.yaml）')
    ap.add_argument('--output',
                    default=os.path.normpath(os.path.join(
                        os.path.dirname(os.path.abspath(__file__)),
                        '..', 'resourse', 'system', 'pinyin_dict.txt')),
                    help='输出词库文件（默认 resourse/system/pinyin_dict.txt）')
    args = ap.parse_args()

    if not os.path.isfile(args.input):
        print(f'错误：找不到源文件 {args.input}', file=sys.stderr)
        return 1

    groups, filtered = parse_dict(args.input)
    if not groups:
        print('错误：未解析到任何词条，检查输入文件格式', file=sys.stderr)
        return 1

    # 按字典序输出拼音（LVGL 前缀匹配要求）；组内按权重降序（常用靠前）
    lines = []
    total_chars = 0
    for py in sorted(groups.keys()):
        entries = sorted(groups[py], key=lambda t: -t[1])  # 权重降序
        mb = ''.join(ch for ch, _ in entries)
        lines.append(f'{py}\t{mb}')
        total_chars += len(entries)

    os.makedirs(os.path.dirname(args.output), exist_ok=True)
    with open(args.output, 'w', encoding='utf-8') as f:
        f.write('# Pinyin dict for LVGL IME — generated by tools/gen_pinyin_dict.py\n')
        f.write(f'# source: {args.input}\n')
        f.write(f'# {len(groups)} pinyin entries, {total_chars} chars (sorted by weight)\n')
        f.write('# format: pinyin<TAB>chars (3-byte UTF-8 each, no separator)\n')
        for line in lines:
            f.write(line + '\n')

    print(f'生成完成: {args.output}')
    print(f'拼音条目: {len(groups)}')
    print(f'总字数: {total_chars}')
    if filtered:
        print(f'过滤 {len(filtered)} 项（不影响词库）:')
        for ch, py, w, reason in filtered[:30]:
            print(f'  {ch} ({py}, {w}) - {reason}')
        if len(filtered) > 30:
            print(f'  ... 等 {len(filtered)} 项')
    return 0


if __name__ == '__main__':
    sys.exit(main())
