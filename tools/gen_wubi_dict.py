#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
从 Rime 五笔词库提取「五笔编码 → 单字」映射，生成 ESP32-P4 LVGL IME 五笔词库。

数据源：Rime 五笔86极点码表 (wubi86_jidian.dict.yaml)
  - 格式：词<TAB>编码<TAB>权重（columns: text/code/weight/stem）
  - 编码 1-4 码（a-z），含一级简码

输出：reserces/system/wubi_dict.txt（FAT 上传到 /root/system/）
  - 格式：编码<TAB>汉字直接连接（无分隔符，紧凑，每字 3 字节 UTF-8）
  - 编码按字典序排列（LVGL 前缀匹配要求，短码在前：工 a 在 式 aa 之前）
  - 组内按权重降序（常用字靠前）；同码多字（重码）拼进一个条目，翻页浏览

约束：
  - 仅单字（LVGL 每候选固定 3 字节，不支持多字词）
  - 过滤非 3 字节 UTF-8 字（CJK 扩展区）
  - 编码仅 [a-z]+

用法：
  python3 tools/gen_wubi_dict.py [--input 源文件] [--output 输出文件]
"""

import argparse
import os
import re
import sys
from collections import defaultdict

CODE_RE = re.compile(r'^[a-z]+$')


def parse_dict(path):
    """解析 Rime 五笔 .dict.yaml，返回 ({code: [(char, weight)]}, 过滤清单)"""
    groups = defaultdict(list)
    filtered = []  # (char, code, weight, reason)
    with open(path, encoding='utf-8') as f:
        for line in f:
            line = line.rstrip('\n').rstrip('\r')
            if not line or line.startswith('#') or \
               line.startswith('---') or line.startswith('...'):
                continue
            parts = line.split('\t')
            if len(parts) < 2:
                continue
            ch, code = parts[0], parts[1]
            weight = int(parts[2].strip()) if len(parts) >= 3 and parts[2].strip().isdigit() else 0

            # 仅单字（LVGL 候选固定 3 字节，多字词无法表示）
            if len(ch) != 1:
                continue
            # 过滤非 3 字节 UTF-8（CJK 扩展区等）
            if len(ch.encode('utf-8')) != 3:
                filtered.append((ch, code, weight, '非3字节UTF-8'))
                continue
            # 编码校验（五笔码 a-z，1-4 码）
            if not CODE_RE.fullmatch(code):
                filtered.append((ch, code, weight, '非法编码'))
                continue

            groups[code].append((ch, weight))
    return groups, filtered


def main():
    ap = argparse.ArgumentParser(description='生成 LVGL IME 五笔词库')
    ap.add_argument('--input',
                    default=os.path.expanduser('~/.config/ibus/rime/wubi86_jidian.dict.yaml'),
                    help='Rime 五笔码表源文件（默认 ~/.config/ibus/rime/wubi86_jidian.dict.yaml）')
    ap.add_argument('--output',
                    default=os.path.normpath(os.path.join(
                        os.path.dirname(os.path.abspath(__file__)),
                        '..', 'reserces', 'system', 'wubi_dict.txt')),
                    help='输出词库文件（默认 reserces/system/wubi_dict.txt）')
    args = ap.parse_args()

    if not os.path.isfile(args.input):
        print(f'错误：找不到源文件 {args.input}', file=sys.stderr)
        return 1

    groups, filtered = parse_dict(args.input)
    if not groups:
        print('错误：未解析到任何词条，检查输入文件格式', file=sys.stderr)
        return 1

    # 按字典序输出编码（LVGL 前缀匹配要求，短码在前）；组内按权重降序（常用靠前）
    lines = []
    total_chars = 0
    for code in sorted(groups.keys()):
        entries = sorted(groups[code], key=lambda t: -t[1])  # 权重降序
        mb = ''.join(ch for ch, _ in entries)
        lines.append(f'{code}\t{mb}')
        total_chars += len(entries)

    os.makedirs(os.path.dirname(args.output), exist_ok=True)
    with open(args.output, 'w', encoding='utf-8') as f:
        f.write('# Wubi dict for LVGL IME — generated by tools/gen_wubi_dict.py\n')
        f.write(f'# source: {args.input}\n')
        f.write(f'# {len(groups)} code entries, {total_chars} chars (single-char only, sorted by weight)\n')
        f.write('# format: code<TAB>chars (3-byte UTF-8 each, no separator)\n')
        for line in lines:
            f.write(line + '\n')

    print(f'生成完成: {args.output}')
    print(f'编码条目: {len(groups)}')
    print(f'总字数: {total_chars}')
    if filtered:
        print(f'过滤 {len(filtered)} 项（不影响词库）:')
        for ch, code, w, reason in filtered[:30]:
            print(f'  {ch} ({code}, {w}) - {reason}')
        if len(filtered) > 30:
            print(f'  ... 等 {len(filtered)} 项')
    return 0


if __name__ == '__main__':
    sys.exit(main())
