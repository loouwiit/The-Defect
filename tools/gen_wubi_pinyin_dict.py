#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
混合五笔与拼音词库：优先五笔，其次拼音兜底。

背景：五笔码表每个码通常只有 1-2 个字（重码少），候选面板大量空位；
混合拼音后，同一个码下「五笔字在前 + 拼音字补在后」，候选更丰富，
且五笔码记不住时可直接用拼音输入（拼音码也包含在词库中）。

混合规则（按码）：
  1. 五笔字完整保留（按 wubi_dict.txt 权重序），排在最前
  2. 拼音字按 pinyin_dict.txt 权重序追加，跳过五笔已有的字（去重）
  3. 编码 = 五笔编码 ∪ 拼音编码，按字典序输出（LVGL 前缀匹配要求，短码在前）

输入：
  - reserces/system/wubi_dict.txt   （tools/gen_wubi_dict.py 生成）
  - reserces/system/pinyin_dict.txt （tools/gen_pinyin_dict.py 生成）
输出：
  - reserces/system/wubi_pinyin_dict.txt

用法：
  python3 tools/gen_wubi_pinyin_dict.py [--wubi 五笔词库] [--pinyin 拼音词库] [--output 输出]
"""

import argparse
import os
import sys
from collections import OrderedDict


def load_dict(path):
    """读取词库文件，返回 {code: [chars]}（保持文件内顺序 = 权重降序）"""
    result = OrderedDict()
    with open(path, encoding='utf-8') as f:
        for line in f:
            line = line.rstrip('\n')
            if not line or line.startswith('#'):
                continue
            parts = line.split('\t', 1)
            if len(parts) != 2:
                continue
            code, mb = parts
            # mb 每 3 字节一个汉字
            chars = [mb[i:i + 3] for i in range(0, len(mb), 3)]
            result[code] = chars
    return result


def main():
    ap = argparse.ArgumentParser(description='混合五笔与拼音词库（五笔优先，拼音兜底）')
    res = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                        '..', 'reserces', 'system'))
    ap.add_argument('--wubi', default=os.path.join(res, 'wubi_dict.txt'),
                    help='五笔词库（默认 reserces/system/wubi_dict.txt）')
    ap.add_argument('--pinyin', default=os.path.join(res, 'pinyin_dict.txt'),
                    help='拼音词库（默认 reserces/system/pinyin_dict.txt）')
    ap.add_argument('--output', default=os.path.join(res, 'wubi_pinyin_dict.txt'),
                    help='混合词库输出（默认 reserces/system/wubi_pinyin_dict.txt）')
    args = ap.parse_args()

    for p in (args.wubi, args.pinyin):
        if not os.path.isfile(p):
            print(f'错误：找不到源文件 {p}', file=sys.stderr)
            return 1

    wubi = load_dict(args.wubi)
    pinyin = load_dict(args.pinyin)
    if not wubi or not pinyin:
        print('错误：词库为空，检查输入文件', file=sys.stderr)
        return 1

    # ── 混合：五笔优先，拼音补充（去重） ──
    mixed = {}
    wubi_only = 0
    pinyin_only = 0
    merged = 0
    for code, chars in wubi.items():
        mixed[code] = list(chars)
        wubi_only += 1
    for code, chars in pinyin.items():
        if code not in mixed:
            mixed[code] = list(chars)
            pinyin_only += 1
        else:
            existing = set(mixed[code])
            for ch in chars:
                if ch not in existing:
                    mixed[code].append(ch)
                    existing.add(ch)
            merged += 1

    # ── 按字典序输出（LVGL 前缀匹配要求，短码在前） ──
    lines = []
    total_chars = 0
    for code in sorted(mixed.keys()):
        mb = ''.join(mixed[code])
        lines.append(f'{code}\t{mb}')
        total_chars += len(mixed[code])

    os.makedirs(os.path.dirname(args.output), exist_ok=True)
    with open(args.output, 'w', encoding='utf-8') as f:
        f.write('# Wubi+Pinyin mixed dict for LVGL IME — generated by tools/gen_wubi_pinyin_dict.py\n')
        f.write(f'# wubi:    {args.wubi}\n')
        f.write(f'# pinyin:  {args.pinyin}\n')
        f.write(f'# {len(mixed)} code entries, {total_chars} chars (wubi first, pinyin fallback, dedup)\n')
        f.write('# format: code<TAB>chars (3-byte UTF-8 each, no separator)\n')
        for line in lines:
            f.write(line + '\n')

    print(f'生成完成: {args.output}')
    print(f'编码条目: {len(mixed)}（纯五笔 {wubi_only} + 拼音独有 {pinyin_only} + 重合补字 {merged}）')
    print(f'总字数: {total_chars}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
